import { invoke } from "@tauri-apps/api/core";
import { spawnShell } from "@/lib/terminal";
import { useMcpStore } from "@/stores/useMcpStore";
import { usePluginStore } from "@/stores/usePluginStore";
import { useSessionStore } from "@/stores/useSessionStore";
import { TerminalGrid } from "../TerminalGrid";

const invokeMock = vi.mocked(invoke);
const spawnShellMock = vi.mocked(spawnShell);

describe("TerminalGrid — launching without Full Disk Access", () => {
  beforeEach(() => {
    invokeMock.mockReset();
    invokeMock.mockImplementation(async (cmd: string) => {
      if (cmd === "generate_project_hash") return "hash";
      if (cmd === "list_claude_sessions") {
        return { sessions: [], total_found: 0, truncated: false, unreadable: 0 };
      }
      return [];
    });
    let nextId = 100;
    spawnShellMock.mockReset();
    spawnShellMock.mockImplementation(async () => nextId++);
    useSessionStore.setState({ sessions: [], samuraiBySessionId: {}, parkedSessionIds: [] });
    useMcpStore.setState({ projectServers: {} });
    usePluginStore.setState({ projectSkills: {}, projectPlugins: {} });
  });

  it("launches once when the access dialog was dismissed for good", async () => {
    localStorage.setItem("maestro:permissions:fda-dismissed", "true");
    checkFullDiskAccess.mockClear();
    render(<TerminalGrid projectPath="/Users/me/Desktop/proj" tabId="tab-1" isActive />);

    await act(async () => {
      fireEvent.click(screen.getByRole("button", { name: "Launch Session" }));
    });

    await screen.findByTestId("terminal-view");
    expect(spawnShellMock).toHaveBeenCalledTimes(1);
    // One check at the button and one in the dialog store, then it proceeds.
    expect(checkFullDiskAccess.mock.calls.length).toBeLessThanOrEqual(3);
    localStorage.removeItem("maestro:permissions:fda-dismissed");
  });
});
